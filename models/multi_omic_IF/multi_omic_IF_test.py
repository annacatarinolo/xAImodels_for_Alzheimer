import shap
import numpy as np
import pandas as pd
import mudata as md
import mofax as mofa
import seaborn as sns
from anndata import AnnData
import matplotlib.pyplot as plt
import matplotlib.patches as mpatches
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, matthews_corrcoef, confusion_matrix

#Loading the test datasets of the gene expression values and mutations,as well as y_train e y_test
de_genes_test = pd.read_csv("datasets/multi_omic_IF/de_genes_norm_test.csv", index_col=0) 
snp_test= pd.read_csv("datasets/multi_omic_IF/snp_select_norm_test.csv", index_col=0)

y_train= y_train= pd.read_csv("datasets/multi_omic_IF/y_train.csv", index_col=0)
y_test= pd.read_csv("datasets/multi_omic_IF/y_test.csv", index_col=0)

n_factors= 50

# Loading the model previously trained and saved
model = mofa.mofa_model(f"models/multi_omic_IF//model_final_{n_factors}_last.hdf5")
# Visualizzo i campioni del modello
model.get_samples()

# Extracting the weight matrices trained by the model
trained_weights = model.get_weights(df=True)
trained_weights_ge = model.get_weights(df=True, views='genes')
trained_weights_mut=model.get_weights(df=True, views='mut')

# Extracting the factor matrix created by the model
Z_train = model.get_factors(df=True)

# Creating test AnnData
adata_ge_test = AnnData(X=de_genes_test)
adata_snp_test = AnnData(X=snp_test)

# Creating test MuData
mdata_test = md.MuData({'genes': adata_ge_test, 'mut': adata_snp_test})
# mdata_test

# Creating test MuData as a DataFrame, will be used in the calculation of the pseudo-inverse
mdata_test_all = mdata_test[mdata_test.mod_names[0]].to_df()
for elem in mdata_test.mod_names[1:]:
  if elem != 'genes':
    mdata_test_all = pd.concat((mdata_test_all,mdata_test[elem].to_df()),axis=1)
mdata_test_all

#viewing the observations, i.e. the patients in the MuData test
mdata_test['genes'].obs

# # COMPUTING THE PSEUDOINVERSE
# # Here I calculate the projection of the test samples into the factor space
Z_test = np.dot(mdata_test_all, np.linalg.pinv(trained_weights.T) )
Z_test_df= pd.DataFrame(Z_test, index= de_genes_test.index, columns=Z_train.columns)

# Defining the classifier
clf= RandomForestClassifier(random_state=42, n_estimators=200, max_depth=8)
clf_name="RandomForest"

# Training the classifier using the factor matrix generated by the model based on the training patients
clf.fit(Z_train, y_train)

# Prediction on the test dataset, which is the
# new factor matrix resulting from the pseudo-inverse
y_pred = clf.predict(Z_test_df)

# Computing the scores
accuracy = accuracy_score(y_test, y_pred)
precision= precision_score(y_test, y_pred)
recall= recall_score(y_test, y_pred)
f1_score= f1_score(y_test, y_pred)
mcc= matthews_corrcoef(y_test, y_pred)
cm= confusion_matrix(y_test, y_pred)

scores = pd.Series([accuracy, precision, recall, f1_score, mcc], index= ['accuracy', 'precision', 'recall', 'F1_score', 'MCC'])
print(scores)

# Initializing SHAP for explainability
shap.initjs()

# Creating the explainer
explainer = shap.TreeExplainer(clf)

#SECOND PLOT: bar chart of the overall SHAP values
# calculation of SHAP values for the test factor matrix
shap_values = explainer.shap_values(Z_test_df)

# Plot the SHAP values, colour-coding
# the factors associated with genes and those associated with SNPs
feature_names = Z_test_df.columns
shap_mean = np.abs(shap_values).mean(axis=(0, 2))

df_shap = pd.DataFrame({
    'feature': feature_names,
    'importance': shap_mean
})

df_shap = df_shap.sort_values('importance', ascending=False).head(30)
df_shap= df_shap.set_index(df_shap.columns[0])

#Repeat the lines of code to obtain r2 as in the training phase. Colours are assigned based on these values
r2= model.get_r2()
r2= r2.set_index('Factor')
r2= r2.drop('Group', axis=1)
r2 = r2.reset_index()
r2 = r2.loc[r2.groupby('Factor')['R2'].idxmax()]
r2 = r2.sort_index()
r2= r2.set_index('Factor')
r2 = r2.iloc[:30]
r2['R2_log'] = np.log1p(r2['R2'])

#Definig the dict linking the features(factors) with the colors(views)
feature_to_view = r2['View'].to_dict()

df_shap['views'] = df_shap.index.map(feature_to_view)

#Colouring the factors according to the views (SNPs and genes) and add the legend
color_map = {'genes': 'orange', 'mut': 'blue'}
colors= r2['View'].map(color_map)

colors= df_shap['views'].map(color_map)

legend_handles = [
    mpatches.Patch(color='orange', label='genes'),
    mpatches.Patch(color='blue', label='mut')
]

plt.figure(figsize=(8,6))
plt.bar(df_shap.index, df_shap['importance'], color=colors)
plt.grid(False)
plt.tight_layout()
plt.xticks(rotation=45, fontsize=10)
plt.ylabel('SHAP_values', fontsize=9)
plt.legend(handles=legend_handles, title="Views", fontsize=12,
    title_fontsize=14)
plt.show()

#THIRD PLOT: a heatmap that links the top 5 factors according to SHAP to their corresponding biological features
# Creating a list of the 5 most important factors according to the SHAP plot
factors = [1, 6, 10, 24, 29]

# creating a dictionary that associates the 10 features with the highest weights with these factors
top_features = {}

for f in factors:
    col = trained_weights.columns[f-1]
    
    top = trained_weights[col].abs().nlargest(10)
    selected = trained_weights.loc[top.index, col]
    
    top_features[f] = selected

# Creating the list of the most important features
top_features_list= top_features[1].index.append(top_features[6].index).append(top_features[29].index).append(top_features[24].index).append(top_features[10].index).drop_duplicates()

# creating the subset for the plot that associates the features with the factors
subset = trained_weights.loc[list(top_features_list), ['Factor1','Factor6', 'Factor29', 'Factor24', 'Factor10']]

# Creating a function to normalise the weights from 0 to 1, i.e. in absolute values
def normalize_abs_01(series):
    series = series.astype(float)
    
    abs_series = series.abs()
    max_val = abs_series.max()
    
    if max_val == 0:
        return pd.Series(0, index=series.index)
    
    return abs_series / max_val

# Applying the function to each series in the dictionary, and then to each factor
subset1_norm=normalize_abs_01(top_features[1])
subset6_norm=normalize_abs_01(top_features[6])
subset10_norm=normalize_abs_01(top_features[10]) 
subset24_norm=normalize_abs_01(top_features[24])
subset29_norm=normalize_abs_01(top_features[29])

# Creating the dataframe with the normalised values and generate a heatmap that plots each of the top 5 factors (x-axis)
# against the 10 most significant biological features (y-axis)
df_normalized= pd.concat([subset1_norm, subset6_norm, subset29_norm, subset24_norm, subset10_norm], axis=1)

plt.figure(figsize=(15, 15))
sns.set(font_scale=1.5)

ax= sns.heatmap(df_normalized, cmap='Reds',linewidths=0.2)

ax.set_xticks(range(len(df_normalized.columns)))
ax.set_xticks(np.arange(df_normalized.shape[1]) + 0.5)
ax.set_xticklabels(df_normalized.columns, ha='center')
ax.set_yticklabels(df_normalized.index)

plt.title("Top features per Factor 1, 6, 29, 24, 10")
plt.tight_layout()
plt.show()